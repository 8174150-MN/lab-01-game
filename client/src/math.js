// Математичний вектор з методами, які створюють нові об'єкти, а не змінюють аргументи.
export class Vector2 {
  // Конструктор приймає координати й за замовчуванням створює нульовий вектор.
  constructor(x = 0, y = 0) {
    this.x = x; // Зберігаємо горизонтальну складову.
    this.y = y; // Зберігаємо вертикальну складову.
  } // Завершуємо створення вектора.

  // Додаємо інший вектор і повертаємо новий результат.
  add(other) {
    return new Vector2(this.x + other.x, this.y + other.y);
  } // Оригінальні вектори лишаються незмінними.

  // Віднімаємо інший вектор і повертаємо новий результат.
  sub(other) {
    return new Vector2(this.x - other.x, this.y - other.y);
  } // Оригінальні вектори лишаються незмінними.

  // Множимо обидві координати на число.
  scale(amount) {
    return new Vector2(this.x * amount, this.y * amount);
  } // Повертаємо окремий вектор.

  // Повертаємо довжину вектора.
  length() {
    return Math.hypot(this.x, this.y);
  } // hypot рахує корінь із суми квадратів.

  // Залишаємо старе ім'я методу для сумісності з наявним кодом.
  magnitude() {
    return this.length();
  } // Обидва імені дають однакову довжину.

  // Повертаємо одиничний вектор у тому самому напрямку.
  normalize() {
    const size = this.length(); // Обчислюємо довжину один раз.
    return size === 0 ? new Vector2() : this.scale(1 / size); // Нульовий вектор не ділиться на нуль.
  } // Завершуємо нормалізацію.

  // Обертаємо вектор на кут у радіанах.
  rotate(angle) {
    const cos = Math.cos(angle); // Косинус потрібен для повороту по X.
    const sin = Math.sin(angle); // Синус потрібен для повороту по Y.
    return new Vector2(this.x * cos - this.y * sin, this.x * sin + this.y * cos); // Повертаємо координати після обертання.
  } // Завершуємо обертання.

  // Повертаємо скалярний добуток двох векторів.
  dot(other) {
    return this.x * other.x + this.y * other.y;
  } // Результат використовується для проєкцій.

  // Обчислюємо відстань до іншого вектора.
  dist(other) {
    return this.sub(other).length();
  } // Спершу отримуємо різницю, потім її довжину.

  // Створюємо одиничний вектор із заданого кута.
  static fromAngle(angle) {
    return new Vector2(Math.cos(angle), Math.sin(angle));
  } // Кут нуль спрямований праворуч.
} // Завершуємо клас вектора.
