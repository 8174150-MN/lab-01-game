// Клієнт і сервер користуються одним незмінним вектором зі shared-пакета.
export { Vector2 } from '@dogfight/shared/vector';

// Зберігаємо векторні координати сутності в стабільному об'єкті між кадрами.
export class MutableVector2 {
  #x: number; // Внутрішні координати змінюються лише методом set.
  #y: number; // Зовнішній код читає координати через геттери.

  // Створюємо позицію або швидкість для об'єкта сцени.
  constructor(x = 0, y = 0) {
    this.#x = x; // Записуємо початкову координату X.
    this.#y = y; // Записуємо початкову координату Y.
  } // Завершуємо створення вектора стану.

  // Повертаємо X без можливості прямого присвоєння.
  get x(): number {
    return this.#x; // Публічний інтерфейс лишається тільки для читання.
  } // Завершуємо геттер X.

  // Повертаємо Y без можливості прямого присвоєння.
  get y(): number {
    return this.#y; // Публічний інтерфейс лишається тільки для читання.
  } // Завершуємо геттер Y.

  // Оновлюємо координати на місці без створення нового вектора.
  set(x: number, y: number): void {
    this.#x = x; // Перезаписуємо X у тому самому об'єкті.
    this.#y = y; // Перезаписуємо Y у тому самому об'єкті.
  } // Завершуємо повторне використання вектора.
} // Завершуємо вектор стану сутності.
