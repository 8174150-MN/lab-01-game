// Цей файл використовується і на сервері (Node.js), і в браузері клієнта.

// Константа швидкості для всіх кораблів (щоб легко було змінювати баланс)
const SHIP_SPEED = 200;
// Швидкість обертання корабля (радіани на секунду)
const TURN_SPEED = Math.PI;

// Головна функція оновлення стану одного гравця на основі його вводу
export function applyInput(playerState, input, dt) {
  // dt - це delta time, час, що пройшов з минулого кадру в секундах (наприклад, 0.033 для 30 FPS)

  // Якщо в input є команда повороту вліво (-1)
  if (input.turn === -1) {
    // Зменшуємо кут повороту корабля, множачи на швидкість і dt (незалежність від фреймрейту)
    playerState.angle -= TURN_SPEED * dt;
  }
  // Якщо в input є команда повороту вправо (1)
  if (input.turn === 1) {
    // Збільшуємо кут повороту корабля
    playerState.angle += TURN_SPEED * dt;
  }

  // Якщо в input натиснуто газ (рух вперед)
  if (input.gas) {
    // Вираховуємо вектор руху по осі X за допомогою косинуса кута
    // Множимо на швидкість і dt, додаємо до поточної позиції x
    playerState.x += Math.cos(playerState.angle) * SHIP_SPEED * dt;
    // Вираховуємо вектор руху по осі Y за допомогою синуса кута
    // Множимо на швидкість і dt, додаємо до поточної позиції y
    playerState.y += Math.sin(playerState.angle) * SHIP_SPEED * dt;
  }

  // Оновлюємо номер останнього обробленого інпуту для цього гравця
  // Це критично для "звірки" (Reconciliation) на клієнті
  playerState.lastProcessedSeq = input.seq;
}

// Простий детермінований генератор псевдовипадкових чисел (LCG)
// Потрібен, бо Math.random() дасть різні результати на клієнті і сервері
export function seededRandom(seed) {
  // Формула лінійного конгруентного генератора
  seed = (seed * 9301 + 49297) % 233280;
  // Повертаємо число від 0 до 1
  return seed / 233280;
}
