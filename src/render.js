// Функція малювання, де ctx - це 2D-пензлик нашого полотна
export function render(ctx, ship, canvasWidth, canvasHeight) {
    // Стираємо все з екрану перед малюванням наступного кадру (працює як гумка)
    ctx.clearRect(0, 0, canvasWidth, canvasHeight);
    
    // Зберігаємо базову, неторкану координатну сітку екрану
    ctx.save();
    
    // Пересуваємо центр сітки екрану в поточну позицію корабля і крутимо її під кутом його нахилу
    ctx.translate(ship.x, ship.y);
    ctx.rotate(ship.angle);

    // Починаємо створення контуру фігури (наш корабель-трикутник)
    ctx.beginPath();
    ctx.moveTo(20, 0);       // Переміщуємо пензлик у точку носа корабля
    ctx.lineTo(-15, -15);    // Малюємо лінію до лівого крила
    ctx.lineTo(-10, 0);      // Лінія до центру хвоста
    ctx.lineTo(-15, 15);     // Лінія до правого крила
    ctx.closePath();         // Замикаємо останню точку з першою (з носом)

    ctx.strokeStyle = '#00ffcc'; // Задаємо неоновий бірюзовий колір ліній
    ctx.lineWidth = 2;           // Товщина ліній
    ctx.stroke();                // Фактично обводимо побудований контур на екрані

    // Якщо натиснуто газ, малюємо помаранчеву лінію вогню ззаду
    if (ship.isThrusting) {
        ctx.beginPath();
        ctx.moveTo(-12, 0);
        // Додаємо випадковість (Math.random) до довжини вогню, щоб створити ефект миготіння
        ctx.lineTo(-25 - Math.random() * 10, 0);
        ctx.strokeStyle = '#ff6600';
        ctx.stroke();
    }
    
    // Повертаємо сітку до нормального стану, щоб наступні об'єкти не малювались криво
    ctx.restore();
}